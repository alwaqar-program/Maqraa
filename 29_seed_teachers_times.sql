-- ============================================================
-- 29_seed_teachers_times.sql — إدخال المسمعات وأوقاتهن
-- تسنيم (٨س)، روابي القريفة (٤س)، روان (٤س)، نورة الشمّري (٤س)،
-- وزهرة وميمونة الزكري (١٢س لكل واحدة) مسمعتا الختمة الدورية —
-- تُربطان بمسار الختمة الدورية/الأسبوعية تلقائيًا.
-- الأيام: 0=الأحد 1=الاثنين 2=الثلاثاء 3=الأربعاء 4=الخميس 5=الجمعة 6=السبت
-- آمن لإعادة التنفيذ (لا يكرر مسمعة ولا موعدًا موجودًا).
-- ============================================================

-- 1) المسمعات (إن لم تكن موجودة)
INSERT INTO public.teachers (full_name)
SELECT v.name
FROM (VALUES
  ('تسنيم'),
  ('روابي القريفة'),
  ('روان'),
  ('نورة الشمّري'),
  ('زهرة'),
  ('ميمونة الزكري')
) AS v(name)
WHERE NOT EXISTS (SELECT 1 FROM public.teachers t WHERE t.full_name = v.name);

-- 2) ربط مسمعتي الختمة الدورية بالمسار (يُتعرف عليه بالاسم: دورية/أسبوعية)
UPDATE public.teachers
SET track_id = (
  SELECT id FROM public.tracks
  WHERE name LIKE '%دوري%' OR name LIKE '%أسبوعي%'
  ORDER BY sort_order LIMIT 1
)
WHERE full_name IN ('زهرة', 'ميمونة الزكري');

-- 3) أوقات التوفر
INSERT INTO public.availability_slots (teacher_id, weekday, start_time, end_time)
SELECT t.id, v.weekday, v.s::time, v.e::time
FROM (VALUES
  -- تسنيم: الاثنين/الثلاثاء/الخميس ٥-٧ صباحًا + الاثنين/الثلاثاء ٧-٨ مساءً = ٨س
  ('تسنيم', 1, '05:00', '07:00'),
  ('تسنيم', 2, '05:00', '07:00'),
  ('تسنيم', 4, '05:00', '07:00'),
  ('تسنيم', 1, '19:00', '20:00'),
  ('تسنيم', 2, '19:00', '20:00'),
  -- روابي القريفة: الجمعة والسبت ١٢:٣٠-٢:٣٠ ظهرًا = ٤س
  ('روابي القريفة', 5, '12:30', '14:30'),
  ('روابي القريفة', 6, '12:30', '14:30'),
  -- روان: الجمعة والسبت ٥-٧ صباحًا = ٤س
  ('روان', 5, '05:00', '07:00'),
  ('روان', 6, '05:00', '07:00'),
  -- نورة الشمّري: الجمعة والسبت ٥-٧ صباحًا = ٤س
  ('نورة الشمّري', 5, '05:00', '07:00'),
  ('نورة الشمّري', 6, '05:00', '07:00'),
  -- زهرة (ختمة دورية): يوميًا من الاثنين إلى السبت ٥-٧ صباحًا = ١٢س
  ('زهرة', 1, '05:00', '07:00'),
  ('زهرة', 2, '05:00', '07:00'),
  ('زهرة', 3, '05:00', '07:00'),
  ('زهرة', 4, '05:00', '07:00'),
  ('زهرة', 5, '05:00', '07:00'),
  ('زهرة', 6, '05:00', '07:00'),
  -- ميمونة الزكري (ختمة دورية): يوميًا من الاثنين إلى السبت ٧-٩ صباحًا = ١٢س
  ('ميمونة الزكري', 1, '07:00', '09:00'),
  ('ميمونة الزكري', 2, '07:00', '09:00'),
  ('ميمونة الزكري', 3, '07:00', '09:00'),
  ('ميمونة الزكري', 4, '07:00', '09:00'),
  ('ميمونة الزكري', 5, '07:00', '09:00'),
  ('ميمونة الزكري', 6, '07:00', '09:00')
) AS v(name, weekday, s, e)
JOIN public.teachers t ON t.full_name = v.name
WHERE NOT EXISTS (
  SELECT 1 FROM public.availability_slots a
  WHERE a.teacher_id = t.id AND a.weekday = v.weekday
    AND a.start_time = v.s::time AND a.end_time = v.e::time
);

-- 4) تحقق: مجموع ساعات كل مسمعة (المتوقع: تسنيم 8، روابي 4، روان 4، نورة 4، زهرة 12، ميمونة 12)
SELECT t.full_name,
       round(sum(extract(epoch FROM (a.end_time - a.start_time)) / 3600)::numeric, 1) AS total_hours,
       tr.name AS linked_track
FROM public.teachers t
LEFT JOIN public.availability_slots a ON a.teacher_id = t.id
LEFT JOIN public.tracks tr ON tr.id = t.track_id
WHERE t.full_name IN ('تسنيم','روابي القريفة','روان','نورة الشمّري','زهرة','ميمونة الزكري')
GROUP BY t.full_name, tr.name
ORDER BY t.full_name;

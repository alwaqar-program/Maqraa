/** خطوات الصفحة الحالية (أطول مطابقة للمسار) */
export function stepsForPath(pathname: string): TourStep[] {
  const hit = [...PAGE_STEPS]
    .sort((a, b) => b.match.length - a.match.length)
    .find(p => pathname === p.match || pathname.startsWith(`${p.match}/`));
  return hit?.steps ?? [];
}
